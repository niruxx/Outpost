import https from 'node:https';
import crypto from 'node:crypto';
import { HttpError } from '../utils/asyncHandler.js';
import { getSetting, setSetting, clearSetting } from './systemSettingsService.js';
import type { ServerRecord } from '../types/index.js';

export const sfValue = (obj: Record<string, any>, key: string): any => obj[key] ?? obj[key[0].toLowerCase() + key.slice(1)];
const tokenKey = (id: string) => `satisfactory_api_token:${id}`;
export function satisfactoryConnected(id: string) { return !!getSetting(tokenKey(id)); }

/** Fixed loopback destination. Self-signed certificates are normal for this local game API. */
export async function satisfactoryCall(server: ServerRecord, fn: string, data: Record<string, unknown> = {}, token = getSetting(tokenKey(server.id)) ?? '', multipart?: { name: string; buffer: Buffer }) {
  if (!token) throw new HttpError(409, 'Connect a Satisfactory application API token first');
  let body = Buffer.from(JSON.stringify({ function: fn, data })), contentType = 'application/json';
  if (multipart) {
    const boundary = `outpost-${crypto.randomUUID()}`;
    body = Buffer.concat([Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="data"\r\nContent-Type: application/json\r\n\r\n${JSON.stringify({ function: fn, data })}\r\n--${boundary}\r\nContent-Disposition: form-data; name="saveGameFile"; filename="${multipart.name}"\r\nContent-Type: application/octet-stream\r\n\r\n`), multipart.buffer, Buffer.from(`\r\n--${boundary}--\r\n`)]);
    contentType = `multipart/form-data; boundary=${boundary}`;
  }
  return new Promise<Record<string, any>>((resolve, reject) => {
    const req = https.request({ hostname: '127.0.0.1', port: server.server_port, path: '/api/v1/', method: 'POST', rejectUnauthorized: false, headers: { Authorization: `Bearer ${token}`, 'Content-Type': contentType, 'Content-Length': body.length }, timeout: 30000 }, (res) => {
      let text = ''; res.setEncoding('utf8');
      res.on('data', (chunk) => { text += chunk; if (text.length > 8 * 1048576) req.destroy(new Error('Satisfactory response is too large')); });
      res.on('error', reject);
      res.on('end', () => {
        let result: Record<string, any>;
        try { result = text ? JSON.parse(text) : {}; } catch { reject(new HttpError(502, 'Satisfactory returned an invalid API response')); return; }
        if ((res.statusCode ?? 500) >= 400 || result.errorCode) { reject(new HttpError(502, result.errorMessage ?? result.errorCode ?? `Satisfactory API returned ${res.statusCode}`)); return; }
        resolve(result.data ?? {});
      });
    });
    req.on('timeout', () => req.destroy(new Error('Satisfactory API request timed out')));
    req.on('error', (err) => reject(new HttpError(502, `Could not reach the local Satisfactory API: ${err.message}`)));
    req.end(body);
  });
}
export async function connectSatisfactory(server: ServerRecord, token: unknown) {
  if (typeof token !== 'string' || !token.trim() || token.length > 8192 || /[\r\n]/.test(token)) throw new HttpError(400, 'Enter an application API token generated by the server');
  await satisfactoryCall(server, 'VerifyAuthenticationToken', {}, token.trim());
  setSetting(tokenKey(server.id), token.trim());
}
export function disconnectSatisfactory(id: string) { clearSetting(tokenKey(id)); }
export async function satisfactoryView(server: ServerRecord) {
  if (!satisfactoryConnected(server.id)) return { connected: false, options: {}, pendingOptions: {}, sessions: [], state: null };
  const [options, sessions, state] = await Promise.all([satisfactoryCall(server, 'GetServerOptions'), satisfactoryCall(server, 'EnumerateSessions'), satisfactoryCall(server, 'QueryServerState')]);
  return {
    connected: true, options: sfValue(options, 'ServerOptions') ?? {}, pendingOptions: sfValue(options, 'PendingServerOptions') ?? {},
    sessions: (sfValue(sessions, 'Sessions') ?? []).map((s: Record<string, any>) => ({ name: sfValue(s, 'SessionName'), saves: (sfValue(s, 'SaveHeaders') ?? []).map((f: Record<string, any>) => ({ name: sfValue(f, 'SaveName'), at: sfValue(f, 'SaveDateTime'), map: sfValue(f, 'MapName') })) })),
    state: sfValue(state, 'ServerGameState') ?? state,
  };
}
export function satisfactoryAction(action: unknown, input: Record<string, unknown>): { fn: string; data: Record<string, unknown> } {
  const name = (value: unknown) => {
    if (typeof value !== 'string' || !value.trim() || value.length > 128 || /[\r\n\0/\\]/.test(value)) throw new HttpError(400, 'Enter a valid server, session or save name');
    return value.trim();
  };
  if (action === 'rename') return { fn: 'RenameServer', data: { ServerName: name(input.name) } };
  if (action === 'save') return { fn: 'SaveGame', data: { SaveName: name(input.name) } };
  if (action === 'load') return { fn: 'LoadGame', data: { SaveName: name(input.name), EnableAdvancedGameSettings: input.advanced === true } };
  if (action === 'create') return { fn: 'CreateNewGame', data: { NewGameData: { SessionName: name(input.name), MapName: '', StartingLocation: '', bSkipOnboarding: true, AdvancedGameSettings: {}, CustomOptionsOnlyForModding: {} } } };
  if (action === 'options') {
    if (!input.options || typeof input.options !== 'object' || Array.isArray(input.options) || Object.keys(input.options).length > 100) throw new HttpError(400, 'Invalid server options');
    for (const [key, value] of Object.entries(input.options)) if (!/^[A-Za-z0-9_.-]{1,128}$/.test(key) || typeof value !== 'string' || value.length > 1000 || /[\r\n\0]/.test(value)) throw new HttpError(400, `Invalid option: ${key}`);
    return { fn: 'ApplyServerOptions', data: { UpdatedServerOptions: input.options } };
  }
  throw new HttpError(400, 'Unknown Satisfactory action');
}
