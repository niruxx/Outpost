import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import express from 'express';
import AdmZip from 'adm-zip';
import { DatabaseSync } from 'node:sqlite';

const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'outpost-backup-storage-'));
process.env.OUTPOST_DATA_DIR = path.join(temp, 'panel');
const { db } = await import('../dist/db/db.js');
const storage = await import('../dist/services/backupStorageService.js');
const backups = await import('../dist/services/backupService.js');
const rewind = await import('../dist/services/rewindService.js');
const servers = await import('../dist/services/serverService.js');
const users = await import('../dist/services/userService.js');
const paths = await import('../dist/utils/paths.js');
const { getDiskUsage } = await import('../dist/services/diskUsageService.js');
const { fetchRemote } = await import('../dist/services/offsiteService.js');
const { backupsRouter } = await import('../dist/routes/backups.routes.js');
const { createToken } = await import('../dist/auth/tokens.js');
const environment = await import('../dist/services/environmentBackupService.js');
let httpServer, exported;
try {
  const { runMigrations } = await import('../dist/db/migrations.js');
  db.exec('ALTER TABLE servers DROP COLUMN backup_directory');
  runMigrations(db); runMigrations(db);
  const admin = users.createUser('storage-admin', 'test-password-123', 'admin');
  const viewer = users.createUser('storage-viewer', 'test-password-123', 'viewer');
  const server = servers.createServerRecord({ name: 'Storage test', platform: 'java', loader: 'vanilla', version: '1.21', minMemoryMb: 128, maxMemoryMb: 512, serverPort: 25565, createdBy: admin.id });
  users.setUserServerAccess(viewer.id, [server.id]);
  const live = paths.instanceDir(server.id);
  await fs.mkdir(path.join(live, 'world'), { recursive: true });
  await fs.writeFile(path.join(live, 'world', 'level.dat'), 'first world');
  await fs.writeFile(path.join(live, 'server.properties'), 'level-name=world\n');
  const snapshot = await backups.createBackup(server.id, 'manual');
  const oldTime = new Date('2020-01-01T00:00:00Z');
  await fs.utimes(backups.resolveBackupPath(server.id, snapshot.fileName), oldTime, oldTime);
  const point = await rewind.createPoint(server, 'manual');
  await new Promise((resolve) => setTimeout(resolve, 10));
  const point2 = await rewind.createPoint(server, 'manual');
  const drive = path.join(temp, 'external-drive'); await fs.mkdir(drive);
  const defaults = storage.backupStorageInfo(server.id);
  const moved = await storage.setBackupStorage(server.id, drive, true);
  assert.equal(moved.changing, false);
  assert.equal(moved.directory, await fs.realpath(drive));
  assert.equal(servers.getServer(server.id).backup_directory, moved.directory);
  assert.equal(storage.backupDir(server.id), path.join(moved.directory, server.id, 'snapshots'));
  assert.equal((await fs.stat(path.join(defaults.snapshots, snapshot.fileName))).isFile(), true, 'Originals must remain');
  assert.equal(backups.listBackups(server.id)[0].createdAt, oldTime.toISOString(), 'Copy must preserve retention chronology');
  assert.equal(rewind.listPoints(server).length, 2);
  assert.equal(await fs.readFile(path.join(moved.rewind, point.id, 'world', 'level.dat'), 'utf8'), 'first world');
  const hard1 = await fs.stat(path.join(moved.rewind, point.id, 'world', 'level.dat'));
  const hard2 = await fs.stat(path.join(moved.rewind, point2.id, 'world', 'level.dat'));
  assert.equal(hard1.ino, hard2.ino, 'Migration must preserve hard links on filesystems that support them');
  await fs.writeFile(path.join(live, 'world', 'level.dat'), 'changed world');
  await backups.restoreBackup(server.id, snapshot.fileName);
  assert.equal(await fs.readFile(path.join(live, 'world', 'level.dat'), 'utf8'), 'first world');
  assert(backups.listSnapshotEntries(server.id, snapshot.fileName).some((entry) => entry.path === 'world/level.dat'));
  await fs.writeFile(path.join(live, 'world', 'level.dat'), 'another change');
  await rewind.restorePoint(server, point.id);
  assert.equal(await fs.readFile(path.join(live, 'world', 'level.dat'), 'utf8'), 'first world');
  await fs.writeFile(path.join(live, 'world', 'level.dat_old'), 'older level data');
  rewind.restoreLevelDat(server, 'world');
  assert.equal(await fs.readFile(path.join(live, 'world', 'level.dat'), 'utf8'), 'older level data');
  const safetyDir = path.join(moved.snapshots, 'file-undo', 'world-rewind', 'world');
  assert((await fs.readdir(safetyDir)).some((name) => name.startsWith('level.dat.before-restore-')));
  assert(!(await fs.readdir(path.join(live, 'world'))).some((name) => name.startsWith('level.dat.before-restore-')));
  const plugins = await import('../dist/services/cs2PluginService.js');
  const pluginRoot = path.join(live, 'game', 'csgo', 'addons', 'counterstrikesharp', 'plugins', 'Example');
  await fs.mkdir(pluginRoot, { recursive: true });
  await fs.writeFile(path.join(pluginRoot, 'settings.json'), '{"value":1}');
  const pluginRel = 'addons/counterstrikesharp/plugins/Example/settings.json';
  plugins.writePluginConfig(server, 'Example', pluginRel, '{"value":2}');
  assert.equal(plugins.readPluginConfig(server, 'Example', pluginRel).hasBackup, true);
  assert.equal(await fs.readFile(storage.fileUndoPath(server.id, `cs2/${pluginRel}.outpost.bak`), 'utf8'), '{"value":1}');
  plugins.revertPluginConfig(server, 'Example', pluginRel);
  assert.equal(await fs.readFile(path.join(pluginRoot, 'settings.json'), 'utf8'), '{"value":1}');
  assert.equal(await fs.readFile(storage.fileUndoPath(server.id, `cs2/${pluginRel}.outpost.bak`), 'utf8'), '{"value":2}');
  const auto = await backups.createBackup(server.id, 'auto');
  const preUpdate = await backups.createBackup(server.id, 'pre-update');
  assert.equal((await fs.stat(path.join(moved.snapshots, auto.fileName))).isFile(), true);
  assert.equal((await fs.stat(path.join(moved.snapshots, preUpdate.fileName))).isFile(), true);
  backups.enforceRetention(server.id, 2);
  assert.equal(backups.listBackups(server.id).length, 2);
  assert(!backups.listBackups(server.id).some((b) => b.fileName === snapshot.fileName));
  const lease = storage.acquireBackupStorage(server.id);
  await assert.rejects(storage.setBackupStorage(server.id, null, true), { status: 409 }); lease();
  await assert.rejects(storage.setBackupStorage(server.id, live, true), { status: 400 });
  await assert.rejects(storage.setBackupStorage(server.id, 'relative/folder', true), { status: 400 });
  await assert.rejects(storage.setBackupStorage(server.id, path.join(temp, 'missing'), true), { status: 400 });

  // A disconnected mount can leave an empty directory. Do not recreate the storage marker there.
  const offline = path.join(temp, 'drive-offline');
  assert.equal(path.dirname(offline), temp); assert.equal(path.dirname(drive), temp);
  await fs.rename(drive, offline); await fs.mkdir(drive);
  assert.equal(storage.backupStorageInfo(server.id).available, false);
  assert.throws(() => storage.backupDir(server.id), { status: 503 });
  await assert.rejects(backups.createBackup(server.id, 'no-fallback'), { status: 503 });
  await assert.rejects(storage.setBackupStorage(server.id, drive, true), { status: 503 });
  assert.deepEqual(await fs.readdir(drive), [], 'Missing drive must not receive replacement backups');
  assert.equal(getDiskUsage(server.id).backupsAvailable, false, 'An unplugged drive must not break instance metrics');
  await fs.rmdir(drive); await fs.rename(offline, drive);

  const zip = new AdmZip(); zip.addFile('restored.txt', Buffer.from('remote'));
  const remoteZip = zip.toBuffer();
  const app = express(); app.use(express.json());
  app.use('/api/servers/:serverId/backups', backupsRouter);
  app.get('/bucket/*', (_req, res) => res.type('zip').send(remoteZip));
  app.use((error, _req, res, _next) => res.status(error.status ?? 500).json({ error: error.message }));
  httpServer = app.listen(0, '127.0.0.1'); await new Promise((resolve) => httpServer.once('listening', resolve));
  const origin = `http://127.0.0.1:${httpServer.address().port}`;
  const remote = { type: 's3', config: { endpoint: origin, region: 'us-east-1', bucket: 'bucket', accessKeyId: 'test', secretAccessKey: 'test', prefix: 'test', pathStyle: true } };
  await fetchRemote(remote, server.id, 'downloaded.zip');
  assert.equal((await fs.stat(path.join(moved.snapshots, 'downloaded.zip'))).isFile(), true);
  const adminToken = createToken(admin.id, admin.username, 'admin'), viewerToken = createToken(viewer.id, viewer.username, 'viewer');
  const request = (token, method = 'GET', body) => fetch(`${origin}/api/servers/${server.id}/backups/storage`, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal((await request(viewerToken)).status, 200);
  assert.equal((await request(viewerToken, 'PUT', { directory: null })).status, 403);
  users.updateUserRole(admin.id, 'viewer');
  assert.equal((await request(adminToken, 'PUT', { directory: null })).status, 403);
  users.updateUserRole(admin.id, 'admin');
  const response = await request(adminToken, 'PUT', { directory: drive, copyExisting: true });
  assert.equal(response.status, 200);
  assert.equal((await response.json()).directory, moved.directory);

  // Portable exports use active archives, without resurrecting pruned originals.
  exported = await environment.exportEnvironment();
  const exportedZip = new AdmZip(exported.filePath);
  assert(exportedZip.getEntry(`backups/${server.id}/downloaded.zip`));
  assert.equal(exportedZip.getEntry(`backups/${server.id}/${snapshot.fileName}`), null);
  assert(exportedZip.getEntry(`rewind/${server.id}/${point.id}/manifest.json`));
  const imported = path.join(temp, 'imported'); await fs.mkdir(imported);
  exportedZip.extractAllTo(imported, true);
  environment.resetImportedBackupStoragePaths(imported);
  const importedDb = new DatabaseSync(path.join(imported, 'outpost.db'));
  assert.equal(importedDb.prepare('SELECT backup_directory FROM servers WHERE id = ?').get(server.id).backup_directory, null); importedDb.close();
  assert.equal(servers.getServer(server.id).backup_directory, moved.directory);

  // Conflicting archives must not be overwritten or change the active setting.
  const conflict = path.join(temp, 'conflict'); await fs.mkdir(conflict);
  await storage.setBackupStorage(server.id, conflict, false);
  await fs.writeFile(path.join(storage.backupDir(server.id), auto.fileName), 'different archive');
  await storage.setBackupStorage(server.id, drive, false);
  await assert.rejects(storage.setBackupStorage(server.id, conflict, true), { status: 409 });
  assert.equal(servers.getServer(server.id).backup_directory, moved.directory);
  // Re-selecting the default layout can merge identical originals and preserves archive access.
  const reset = await storage.setBackupStorage(server.id, null, true);
  assert.equal(reset.directory, null);
  assert(backups.listBackups(server.id).some((b) => b.fileName === auto.fileName));
  // Instance deletion resolves its custom paths before deleting its database record.
  await storage.setBackupStorage(server.id, drive, false);
  servers.deleteServerRecord(server.id);
  await assert.rejects(fs.stat(moved.snapshots), { code: 'ENOENT' });
  console.log('Backup storage migration, snapshots, World Rewind, retention, off-site downloads, missing drives, portable export, conflicts and authorization checks passed');
} finally {
  if (httpServer) await new Promise((resolve) => httpServer.close(resolve));
  if (exported) await fs.rm(exported.filePath, { force: true });
  db.close(); await fs.rm(temp, { recursive: true, force: true });
}
